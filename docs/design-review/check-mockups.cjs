// Run: node check-mockups.cjs <absolute path to playwright module> [browser executable]
// Visual and interaction checks for the standalone design study, not the live app.
const { chromium } = require(process.argv[2] || 'playwright');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.argv[3] ? {executablePath:process.argv[3]} : {})});
  const page = await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  const out=path.join(__dirname,'screenshots');
  fs.mkdirSync(out,{recursive:true});
  const shot=async(name)=>{await page.evaluate(()=>document.querySelector('#toast').classList.remove('visible'));return page.screenshot({path:path.join(out,name),fullPage:true});};
  const screen=async(name)=>page.locator('.screen-switcher [data-screen="'+name+'"]').click();
  await page.goto(pathToFileURL(path.join(__dirname,'index.html')).href);
  await page.locator('h1').waitFor();
  assert.match(await page.locator('.brand img').getAttribute('src'), /link/);
  assert.equal(await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim()), '#4b64f4');
  await shot('01-overview-light.png');
  await page.locator('button[data-pod="0"]').first().click();
  assert.equal(await page.locator('.inspector h2').textContent(),'emails-99d4775f6-56lmg');
  await shot('02-pods-inspector.png');
  await page.locator('#pod-search').fill('app=api');
  assert.equal(await page.locator('#pod-rows tr').count(),3);
  await page.locator('#pod-search').fill('no-such-pod');
  assert.match(await page.locator('#pod-rows').textContent(),/No pods match/);
  await page.locator('[data-action="clear-filter"]').click();
  await page.locator('[data-filter="attention"]').click();
  assert.equal(await page.locator('#pod-rows tr').count(),3);
  await page.locator('[data-filter="all"]').click();
  await page.locator('[data-tab="yaml"]').click();
  assert.match(await page.locator('.yaml-block').textContent(),/namespace: shop/);
  await page.locator('[data-tab="events"]').click();
  assert.match(await page.locator('.timeline').textContent(),/Back-off/);
  await page.locator('[data-tab="overview"]').click();
  await page.locator('[data-action="previous-logs"]').first().click();
  await page.locator('[data-action="theme"]').click();
  await shot('03-logs-dark.png');
  await page.locator('#log-level').selectOption('error');
  assert.equal(await page.locator('.log-line').count(),6);
  await page.locator('#log-search').fill('Startup');
  assert.equal(await page.locator('.log-line').count(),1);
  await page.locator('#log-search').fill('');
  await page.locator('#log-level').selectOption('all');
  await page.locator('#log-instance').selectOption('current');
  assert.match(await page.locator('.log-view').textContent(),/Waiting for container/);
  await page.locator('#log-instance').selectOption('previous');
  await page.keyboard.press('Control+k');
  await page.locator('#command-search').fill(':ctx');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.connect-page').count(),1);
  await page.locator('[data-action="theme"]').click();
  await shot('04-connect.png');
  await page.locator('[data-action="simulate-error"]').click();
  assert.equal(await page.locator('[role="alert"]').count(),1);
  await page.locator('[data-action="connect"]').click();
  assert.equal(await page.locator('#context-select').inputValue(),'staging-eu');
  await page.locator('#context-select').selectOption('production-eu');
  await screen('pods');
  await page.locator('#namespace-select').selectOption('shop');
  await page.locator('#pod-rows [data-pod="0"]').click();
  await page.locator('[data-action="mode"]').click();
  await page.locator('[data-action="toggle-mode"]').click();
  await page.locator('[data-action="delete"]').click();
  assert.equal(await page.locator('#delete-submit').isDisabled(),true);
  await page.locator('#delete-confirm').fill('delete');
  assert.equal(await page.locator('#delete-submit').isDisabled(),false);
  await shot('05-delete-confirmation.png');
  await page.locator('[data-action="close-modal"]').click();
  await page.locator('#connection-select').selectOption('stale');
  assert.equal(await page.locator('.stale-banner').count(),1);
  await page.locator('[data-action="retry"]').click();
  assert.equal(await page.locator('#connection-select').inputValue(),'live');
  await page.locator('#connection-select').selectOption('denied');
  assert.equal(await page.locator('.pod-table').count(),0);
  assert.match(await page.locator('.empty-state').textContent(),/No permission/);
  await shot('06-access-denied.png');
  await page.locator('#connection-select').selectOption('live');
  await screen('brand');
  await shot('07-logo-concepts.png');
  await page.locator('[data-logo="span"]').click();
  await screen('overview');
  assert.match(await page.locator('.brand img').getAttribute('src'),/span/);
  await screen('brand');
  await page.locator('[data-logo="link"]').click();
  await screen('overview');
  // Close transient feedback before taking responsive screenshots.
  await page.evaluate(()=>{document.querySelector('#toast').classList.remove('visible');});
  const responsive=[];
  for(const width of [1024,768,390,320]){
    await page.setViewportSize({width,height:900});
    for(const name of ['overview','pods','logs','connect','brand']){
      await screen(name);
      const sizes=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
      responsive.push({width,screen:name,...sizes});
      assert.ok(sizes.document<=width+1,`${name} overflows at ${width}px: ${sizes.document}`);
      if(width===390&&['overview','pods','brand'].includes(name))await shot('mobile-'+name+'.png');
    }
  }
  assert.deepEqual(errors,[]);
  await browser.close();
  fs.writeFileSync(path.join(__dirname,'verification.json'),JSON.stringify({checked:'Standalone mockup, not production application',checks:['Pod selection','Text and label filtering','Empty result recovery','Attention filter','YAML and event views','Previous/current logs','Log level and text filtering','Command palette keyboard navigation','Context selection','Connection failure/retry','Read-only action state','Guarded deletion dialog','Stale data state','Permission denied state','Logo selection','Responsive document overflow'],responsive,consoleErrors:errors},null,2)+'\n');
  console.log('PASS: mockup interactions, 20 responsive view checks, and no browser JavaScript errors.');
})().catch(error=>{console.error(error);process.exit(1);});
